CREATE DATABASE CPSDB;
USE CPSDB;

CREATE TABLE DEPARTMENT (
    Dept_ID INTEGER PRIMARY KEY,
    Dept_Name VARCHAR(100) NOT NULL,
    HOD_Name VARCHAR(100),
    Contact VARCHAR(20)
);

CREATE TABLE STUDENT (
    Student_ID INTEGER PRIMARY KEY,
    Dept_ID INTEGER NOT NULL,
    Roll_No VARCHAR(30) UNIQUE NOT NULL,
    Name VARCHAR(100) NOT NULL,
    Gender VARCHAR(20),
    Email VARCHAR(100),
    Phone_Number VARCHAR(20),
    CGPA DECIMAL(4,2),
    Backlogs INTEGER DEFAULT 0,
    Passing_Year INTEGER,
    FOREIGN KEY (Dept_ID) REFERENCES DEPARTMENT(Dept_ID)
);

CREATE TABLE SKILL (
    Skill_ID INTEGER PRIMARY KEY,
    Skill_Name VARCHAR(100) UNIQUE NOT NULL
);

CREATE TABLE STUDENT_SKILL (
    Student_ID INTEGER NOT NULL,
    Skill_ID INTEGER NOT NULL,
    PRIMARY KEY (Student_ID, Skill_ID),
    FOREIGN KEY (Student_ID) REFERENCES STUDENT(Student_ID) ON DELETE CASCADE,
    FOREIGN KEY (Skill_ID) REFERENCES SKILL(Skill_ID) ON DELETE CASCADE
);

CREATE TABLE COMPANY (
    Company_ID INTEGER PRIMARY KEY,
    Company_Name VARCHAR(150) NOT NULL,
    Industry VARCHAR(150) NOT NULL,
    Address VARCHAR(255),
    Website VARCHAR(255),
    Contact VARCHAR(20) NOT NULL,
    Email VARCHAR(100) NOT NULL
);

CREATE TABLE JOB_POSTING (
    Job_ID INTEGER PRIMARY KEY,
    Company_ID INTEGER NOT NULL,
    Job_Title VARCHAR(150) NOT NULL,
    Job_Description TEXT,
    Min_CGPA DECIMAL(4,2),
    Allowed_Backlogs INTEGER DEFAULT 0,
    CTC DECIMAL(12,2),
    Job_Location VARCHAR(150),
    Application_Deadline DATE,
    FOREIGN KEY (Company_ID) REFERENCES COMPANY(Company_ID)
);

CREATE TABLE JOB_SKILL (
    Job_ID INTEGER NOT NULL,
    Skill_ID INTEGER NOT NULL,
    Is_Compulsory BOOLEAN DEFAULT FALSE,
    PRIMARY KEY (Job_ID, Skill_ID),
    FOREIGN KEY (Job_ID) REFERENCES JOB_POSTING(Job_ID) ON DELETE CASCADE,
    FOREIGN KEY (Skill_ID) REFERENCES SKILL(Skill_ID) ON DELETE CASCADE
);

CREATE TABLE ONLINE_ASSESSMENT (
    OA_ID INTEGER PRIMARY KEY,
    Company_ID INTEGER UNIQUE NOT NULL,
    OA_Name VARCHAR(150) NOT NULL,
    Passing_Score DECIMAL(5,2) NOT NULL,
    FOREIGN KEY (Company_ID) REFERENCES COMPANY(Company_ID)
);

CREATE TABLE OA_RESULT (
    OA_ID INTEGER NOT NULL,
    Student_ID INTEGER NOT NULL,
    Score DECIMAL(5,2) NOT NULL,
    Is_Passed BOOLEAN NOT NULL,
    PRIMARY KEY (OA_ID, Student_ID),
    FOREIGN KEY (OA_ID) REFERENCES ONLINE_ASSESSMENT(OA_ID) ON DELETE CASCADE,
    FOREIGN KEY (Student_ID) REFERENCES STUDENT(Student_ID) ON DELETE CASCADE
);

CREATE TABLE APPLICATION (
    Application_ID INTEGER PRIMARY KEY,
    Student_ID INTEGER NOT NULL,
    Job_ID INTEGER NOT NULL,
    Applied_Date DATE NOT NULL,
    Current_Status VARCHAR(30) DEFAULT 'Applied',
    FOREIGN KEY (Student_ID) REFERENCES STUDENT(Student_ID),
    FOREIGN KEY (Job_ID) REFERENCES JOB_POSTING(Job_ID),
    UNIQUE (Student_ID, Job_ID),
    UNIQUE (Application_ID, Job_ID)
);

CREATE TABLE RECRUITMENT_ROUND (
    Round_ID INTEGER PRIMARY KEY,
    Job_ID INTEGER NOT NULL,
    Round_Name VARCHAR(100) NOT NULL,
    Round_Type VARCHAR(50),
    Round_Order INTEGER NOT NULL,
    Description TEXT,
    FOREIGN KEY (Job_ID) REFERENCES JOB_POSTING(Job_ID),
    UNIQUE (Job_ID, Round_Order),
    UNIQUE (Round_ID, Job_ID)
);

CREATE TABLE RESULT (
    Result_ID INTEGER PRIMARY KEY,
    Application_ID INTEGER NOT NULL,
    Round_ID INTEGER NOT NULL,
    Job_ID INTEGER NOT NULL,
    Score DECIMAL(7,2),
    Result_Status VARCHAR(30) NOT NULL,
    Remarks TEXT,
    FOREIGN KEY (Application_ID, Job_ID) REFERENCES APPLICATION(Application_ID, Job_ID),
    FOREIGN KEY (Round_ID, Job_ID) REFERENCES RECRUITMENT_ROUND(Round_ID, Job_ID),
    UNIQUE (Application_ID, Round_ID)
);

CREATE TABLE PLACEMENT_OFFER (
    Offer_ID INTEGER PRIMARY KEY,
    Application_ID INTEGER NOT NULL,
    Offered_CTC DECIMAL(12,2),
    Offer_Date DATE,
    Expected_Joining_Date DATE,
    Offer_Status VARCHAR(30) DEFAULT 'Pending',
    FOREIGN KEY (Application_ID) REFERENCES APPLICATION(Application_ID)
);